# Integer (int)
age = 20
print(age)

# Float
height = 5.8
print(height)

# String (str)
name = "Aditi"
print(name)

# Boolean (bool)
is_student = True
print(is_student)

# List
fruits = ["Apple", "Banana", "Mango"]
print(fruits)

# Tuple
coordinates = (10, 20)
print(coordinates)

# Set
colors = {"Red", "Green", "Blue"}
print(colors)

# Dictionary (dict)
student = {
    "name": "Aditi",
    "age": 20,
    "branch": "IT"
}
print(student)

# Complex Number
num = 3 + 4j
print(num)

# NoneType
value = None
print(value)

# Display the type of each variable
print(type(age))
print(type(height))
print(type(name))
print(type(is_student))
print(type(fruits))
print(type(coordinates))
print(type(colors))
print(type(student))
print(type(num))
print(type(value))